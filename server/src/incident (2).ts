import { Router } from 'express';
import rateLimit from 'express-rate-limit';
import { authenticate } from './middleware/auth.js';
import { validate } from './middleware/validate.js';
import { signup, login, logout, me, signupSchema, loginSchema } from './controllers/auth.controller.js';
import * as monitors from './controllers/monitors.controller.js';
import * as system from './controllers/system.controller.js';

const router=Router();
const authLimiter=rateLimit({windowMs:15*60*1000,max:20,standardHeaders:true,legacyHeaders:false,message:{error:{code:'AUTH_RATE_LIMIT',message:'Too many authentication attempts. Try again later.'}}});
const testerLimiter=rateLimit({windowMs:60*1000,max:(req:any)=>req.userPlan==='pro'?120:30,standardHeaders:true,legacyHeaders:false,message:{error:{code:'TESTER_RATE_LIMIT',message:'Request tester limit reached for your plan. Pro includes 120 requests per minute.'}}});
router.get('/health',(_req,res)=>res.json({status:'ok'}));
router.post('/api/auth/signup',authLimiter,validate(signupSchema),signup);
router.post('/api/auth/login',authLimiter,validate(loginSchema),login);
router.post('/api/auth/logout',logout);
router.get('/api/auth/me',authenticate,me);
router.get('/api/overview',authenticate,system.overview);
router.get('/api/monitors',authenticate,monitors.listMonitors);
router.post('/api/monitors',authenticate,monitors.createMonitor);
router.get('/api/monitors/:id',authenticate,monitors.getMonitor);
router.put('/api/monitors/:id',authenticate,monitors.updateMonitor);
router.delete('/api/monitors/:id',authenticate,monitors.deleteMonitor);
router.post('/api/monitors/:id/pause',authenticate,monitors.pauseMonitor);
router.post('/api/monitors/:id/resume',authenticate,monitors.resumeMonitor);
router.post('/api/monitors/:id/check-now',authenticate,monitors.checkMonitorNow);
router.post('/api/monitors/test',authenticate,monitors.testMonitor);
router.get('/api/monitors/:id/checks',authenticate,monitors.getChecks);
router.get('/api/monitors/:id/stats',authenticate,monitors.getStats);
router.get('/api/monitors/:id/series',authenticate,monitors.getSeries);
router.get('/api/incidents',authenticate,system.listIncidents);
router.get('/api/incidents/:id',authenticate,system.getIncident);
router.post('/api/tester/send',authenticate,testerLimiter,system.sendTesterRequest);
router.get('/api/tester/history',authenticate,system.testerHistory);
router.delete('/api/tester/history/:id',authenticate,system.deleteTesterHistory);
router.delete('/api/tester/history',authenticate,system.deleteTesterHistory);
router.put('/api/account',authenticate,system.updateAccount);
router.put('/api/account/password',authenticate,system.updatePassword);
router.delete('/api/account',authenticate,system.deleteAccount);
router.post('/api/plan/upgrade',authenticate,system.upgradePlan);
router.put('/api/account/status-page',authenticate,system.updateStatusPage);
router.get('/api/status/:slug',system.publicStatus);
router.post('/api/alerts/telegram/link',authenticate,system.linkTelegram);
router.delete('/api/alerts/telegram',authenticate,system.unlinkTelegram);
router.post('/api/alerts/test',authenticate,system.testAlert);
router.post('/api/telegram/webhook',system.telegramWebhook);
export default router;
